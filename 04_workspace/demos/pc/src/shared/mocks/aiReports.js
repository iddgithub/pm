export const aiReportStatusOptions = ['全部状态', '待上传', '已上传待发布', '已发布', '已替换']

export function getAiReportSummary(orders) {
  const projectList = orders.flatMap((order) => order.projects)
  return {
    orderCount: orders.length,
    projectCount: projectList.length,
    pendingCount: projectList.filter((item) => item.aiReportStatus === '待上传').length,
    waitingPublishCount: projectList.filter((item) => item.aiReportStatus === '已上传待发布').length,
    publishedCount: projectList.filter((item) => item.aiReportStatus === '已发布' || item.aiReportStatus === '已替换').length,
  }
}

